"""Pack application icons, literals and labels without changing their bytes.

Run after editing ui_icons.h, ui_app.c UI_STRINGS or ui_labels.h.
The generated header makes the normal firmware build independent of Python.
Use --check to verify it is current without rewriting it.
"""
import argparse
import ast
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "mycode/ui_resources_packed.h"


def resources():
    icons = bytes(int(value, 16) for value in re.findall(
        r"0x([0-9a-fA-F]{2})\b", (ROOT / "mycode/ui_icons.h").read_text(encoding="utf-8")))
    assert len(icons) == 4 * 128, "Review the fixed 32x32 XBM icon layout"
    source=(ROOT / "mycode/ui_app.c").read_text(encoding="utf-8").split("#define UI_STRINGS(X)",1)[1].split("typedef struct",1)[0]
    strings=b"".join(ast.literal_eval(value).encode("ascii")+b"\0" for value in re.findall(r'X\(\w+,\s*("(?:[^"\\]|\\.)*")\)',source))
    labels=(ROOT / "mycode/ui_labels.h").read_text(encoding="utf-8")
    dynamic=bytearray()
    for name,count,width in (("S_TXT_AXES_SOURCE",2,10),("S_TXT_WORK_ITEMS_SOURCE",7,21),("S_ENC_LABELS_SOURCE",14,9)):
        body=re.search(r"#define "+name+r"\s+(\{.*?\})",labels,re.S).group(1)
        values=re.findall(r'"(?:[^"\\]|\\.)*"',body)
        assert len(values)==count
        for value in values:
            encoded=ast.literal_eval(value).encode("ascii")+b"\0"
            assert len(encoded)<=width
            dynamic.extend(encoded.ljust(width,b"\0"))
    return icons+strings+dynamic


def pack(raw):
    """Optimal byte cost for the existing eight-flag LZSS format.

    Include flag-byte boundaries in the dynamic program; choosing only the
    longest current match can make the following tokens more expensive.
    The decoder and all restored resource bytes remain unchanged.
    """
    size=len(raw); matches=[]
    for index in range(size):
        length,distance=2,0
        for candidate in range(1,min(4096,index)+1):
            count=0
            while count<18 and index+count<size and raw[index+count]==raw[index+count-candidate]:
                count+=1
            if count>length: length,distance=count,candidate
        matches.append((length,distance))
    cost=[[0]*8 for _ in range(size+1)]; choice=[[1]*8 for _ in range(size)]
    for index in range(size-1,-1,-1):
        length,_=matches[index]
        for bit in range(8):
            next_bit=(bit+1)%8; flag=int(bit==0)
            best=1+flag+cost[index+1][next_bit]
            for count in range(3,length+1):
                candidate=2+flag+cost[index+count][next_bit]
                if candidate<=best: best=candidate;choice[index][bit]=count
            cost[index][bit]=best
    out=bytearray(); index=0;bit=0
    while index<size:
        if bit==0: flag_at=len(out);out.append(0)
        count=choice[index][bit]
        if count==1: out.append(raw[index])
        else:
            out[flag_at]|=1<<bit
            token=((count-3)<<12)|(matches[index][1]-1)
            out.extend((token&255,token>>8))
        index+=count;bit=(bit+1)%8
    return bytes(out)


def unpack(packed, size):
    """Independent round-trip validation, including overlap and token bounds."""
    out = bytearray()
    index = 0
    while len(out) < size:
        flags = packed[index]
        index += 1
        for bit in range(8):
            if len(out) == size:
                break
            if flags & (1 << bit):
                first = packed[index] | (packed[index+1]<<8)
                index += 2
                length = (first >> 12) + 3
                distance = (first & 4095) + 1
                assert distance <= len(out) and len(out) + length <= size
                for _ in range(length):
                    out.append(out[-distance])
            else:
                out.append(packed[index])
                index += 1
    assert index == len(packed)
    return bytes(out)


def generate():
    raw = resources()
    packed = pack(raw)
    assert unpack(packed, len(raw)) == raw
    lines = ["/* Generated by scripts/pack_ui_resources.py; do not edit.",
             " * Source: ui_icons.h pixels, ui_app.c UI_STRINGS, ui_labels.h.",
             f" * Unpacked SHA256: {hashlib.sha256(raw).hexdigest()}", " */",
             "#ifndef UI_RESOURCES_PACKED_H", "#define UI_RESOURCES_PACKED_H", "#include <stdint.h>",
             f"enum {{ UI_RESOURCE_BYTES={len(raw)} }};",
             "static const uint8_t ui_resources_packed[]={"]
    lines += ["    " + ",".join(f"0x{value:02x}" for value in packed[i:i + 16]) + ","
              for i in range(0, len(packed), 16)]
    lines += ["};", "#endif", ""]
    return "\n".join(lines), len(raw), len(packed)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, raw_size, packed_size = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != header:
            raise SystemExit("UI resource header is stale; run python scripts/pack_ui_resources.py")
    else:
        OUTPUT.write_text(header, encoding="utf-8")
    print(f"UI resources {'verified' if args.check else 'generated'}: {raw_size} -> {packed_size} B")
